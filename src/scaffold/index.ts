import { existsSync } from "node:fs";
import { chmod, mkdir } from "node:fs/promises";
import path from "node:path";
import { mergePackageJson } from "../packageJson.ts";
import type { ComponentTree, ScaffoldOptions } from "../types.ts";
import { extractRoutes, loadApiSpec } from "./openapi.ts";
import { renderSuite, toHostRelImport } from "./templates.ts";

export interface ScaffoldResult {
  /** Absolute paths of the files this call wrote. */
  written: string[];
  /** writeOnce files that already existed and were left untouched. */
  kept: string[];
  status: "generated" | "refreshed" | "kept";
  /**
   * Version in the existing marker file's generated-by banner, on a "kept"
   * result. Undefined for a pre-banner suite — the caller must say "unknown
   * version", never substitute its own.
   */
  existingVersion?: string;
  /**
   * host/main.tsx predates the registry split (no `from "./registry"` import),
   * so the kept wrapper never sees newly analysed components. writeOnce is
   * absolute — `--force` included — so the caller must name the escape:
   * delete host/main.tsx and re-run, or port the hand wiring onto an import
   * of ./registry. host/registry.ts is still written, inert beside it.
   */
  preSplitMain?: boolean;
}

/** The generated-by banner the marker file carries; parseExistingVersion reads it back. */
const BANNER_RE = /Generated by flawless-react (\S+)/;

export function parseExistingVersion(markerText: string): string | undefined {
  return BANNER_RE.exec(markerText)?.[1];
}

export async function scaffold(
  tree: ComponentTree,
  opts: ScaffoldOptions,
): Promise<ScaffoldResult> {
  const outDir = path.resolve(opts.outDir);
  // Keyed on a suite already being here, not on the directory existing. The
  // directory is not a usable proxy: ensureClientProviderWrapper mkdirs outDir
  // at core.ts:215, before the task loop at :298, so on any --nextjs run outDir
  // exists by the time this is reached and a bare existsSync would claim a
  // suite on every FIRST run.
  const marker = path.join(outDir, "playwright.config.ts");
  const suiteExists = existsSync(marker);

  // Changed-mode: the run is narrowed, generation is not churned — nothing is
  // written over an existing suite, and the caller reports which version wrote
  // it (from the marker's banner; pre-banner suites have no version to name).
  if (suiteExists && opts.keepExisting) {
    return {
      written: [],
      kept: [],
      status: "kept",
      existingVersion: parseExistingVersion(await Bun.file(marker).text()),
    };
  }

  await mkdir(outDir, { recursive: true });

  // Checked before the write loop only for clarity — the file is writeOnce, so
  // the loop below could not change the verdict either way.
  const mainPath = path.join(outDir, "host", "main.tsx");
  const preSplitMain =
    // Quote- and extension-tolerant: main.tsx is user-owned, so a prettier
    // singleQuote pass or an explicit ./registry.ts import (the suite tsconfig
    // allows importing .ts extensions) must not read as pre-split forever.
    existsSync(mainPath) &&
    !/from\s+['"]\.\/registry(\.ts)?['"]/.test(await Bun.file(mainPath).text());

  const providerImportPath = opts.provider ? toHostRelImport(outDir, opts.provider) : undefined;
  const mockRoutes = opts.apiSpec ? extractRoutes(await loadApiSpec(opts.apiSpec)) : undefined;

  const files = renderSuite({
    tree,
    extraTrees: opts.extraTrees,
    suiteName: opts.suiteName,
    outDir,
    variants: opts.variants,
    ...(opts.heaps ? { heaps: opts.heaps } : {}),
    report: opts.report,
    providerImportPath,
    mockRoutes,
    nextjsHost: opts.nextjsHost,
    mswSetup: opts.mswSetup,
  });

  const written: string[] = [];
  const kept: string[] = [];
  for (const f of files) {
    const abs = path.join(outDir, f.relPath);
    // Not gated on --force, unlike the colocated specs: the point of these
    // files is that no flag rebuilds a tuned budget or hand-wired provider.
    // Delete the file to get a fresh one, same as provider.fixtures.ts.
    if (f.writeOnce && existsSync(abs)) {
      kept.push(abs);
      continue;
    }
    await mkdir(path.dirname(abs), { recursive: true });
    if (f.relPath === "package.json" && existsSync(abs)) {
      await Bun.write(abs, mergePackageJson(await Bun.file(abs).text(), f.content));
      written.push(abs);
      continue;
    }
    await Bun.write(abs, f.content);
    if (f.executable) await chmod(abs, 0o755);
    written.push(abs);
  }
  return { written, kept, status: suiteExists ? "refreshed" : "generated", preSplitMain };
}

export { renderSuite } from "./templates.ts";
