import path from "node:path";
import { expoNotImplemented } from "../expo/refusal.ts";
import { scaffold } from "../scaffold/index.ts";
import { flattenTrees, hostEligibility } from "../scaffold-tests/registry.ts";
import type { RunContext, Task, TaskResult } from "../types.ts";
import { VERSION } from "../version.ts";

export const perfHarness: Task = {
  id: "perf-harness",
  label: "Generate performance testing harness",
  description: "Playwright + React.Profiler + react-scan suite",
  needsTree: true,
  async run(ctx: RunContext): Promise<TaskResult> {
    // Wave 4 was measured and DECLINED, not deferred (2026-09-12, census in
    // docs/archive/backlog-completed-2026-10.md B-16 + docs/archive/2026-09-expo-probes.md): on
    // an expo-router app the component population is route screens, the host
    // cannot mount anything that needs a navigator (renderRouter is
    // jest-bound), and the profile click scenarios are onClick-only — so the
    // measured ceiling on the dogfood app was ~0 of 32 components. A host
    // built anyway would be a red spec on healthy components or a suite that
    // tests nothing. Revisit condition, recorded in the backlog: an adopter
    // with a real components/ directory of non-route, navigator-free
    // components. The one opening — a Metro-served real-app perf lane, using
    // wave 6's infrastructure — is mapped and probe-gated in
    // docs/archive/wave4-metro-perf-plan.md; it stays declined until a probe
    // clears, because on a React-Compiler app the only honest signal is nulled.
    if (ctx.expo) {
      return expoNotImplemented(
        "perf-harness",
        "measured-and-declined 2026-09-12 — ~0 host-mountable components on an " +
          "all-route-screens app; docs/archive/backlog-completed-2026-10.md B-16 records the evidence " +
          "and the revisit condition",
      );
    }
    const [first, ...rest] = ctx.trees;
    if (!first) {
      return {
        id: "perf-harness",
        ok: false,
        outputs: [],
        findings: [],
        summary: "no components to scaffold",
        error: "no components",
      };
    }
    const suiteName = path.basename(path.resolve(ctx.outDir)).replace(/[^a-zA-Z0-9_-]+/g, "-");
    const res = await scaffold(first, {
      outDir: ctx.outDir,
      extraTrees: rest,
      suiteName,
      variants: ctx.variants,
      heaps: ctx.heaps,
      force: ctx.force,
      // An explicit --force outranks changed-mode's keep: forcing IS asking
      // for the regeneration that changed-mode otherwise declines to churn.
      keepExisting: ctx.changed !== undefined && !ctx.force,
      report: ctx.report,
      provider: ctx.provider,
      apiSpec: ctx.apiSpec,
      nextjsHost: ctx.nextjs !== undefined,
      mswSetup: ctx.nextjs !== undefined,
      providerWraps: ctx.providerWraps,
    });
    if (res.status === "kept") {
      return {
        id: "perf-harness",
        ok: true,
        outputs: [],
        findings: [],
        status: "kept",
        summary: `harness kept (generated by flawless-react ${res.existingVersion ?? "unknown version"}, tool is ${VERSION})`,
      };
    }
    // The number of components the host can actually mount, not the number of
    // entry trees. Those differ by more than half in a real app — most of what
    // the sweep finds is a server component or a compound part — and reporting
    // the tree count claimed a coverage the suite never had.
    const flat = flattenTrees([first, ...rest]);
    const hosted = flat.filter((c) => hostEligibility(c.info).eligible);
    const names = hosted.map((c) => c.info.componentName);
    const covered = `${names.length} of ${flat.length} component(s): ${names.join(", ")}`;
    const keptNote =
      res.kept.length > 0
        ? `; kept ${res.kept.map((f) => path.relative(path.resolve(ctx.outDir), f)).join(", ")} (delete one to regenerate it)`
        : "";
    // One-time migration for pre-split suites. writeOnce is absolute (--force
    // included — budgets.json rests on that promise), so the tool cannot fix
    // the monolith itself: host/registry.ts was written inert beside it, and
    // delete-to-regenerate is the escape.
    const migrationNote = res.preSplitMain
      ? "; host/main.tsx predates the registry split and cannot mount newly analysed components" +
        " — delete it and re-run (provider wiring regenerates from --provider), or port your" +
        ' hand wiring and import "./registry"'
      : "";
    if (res.preSplitMain) {
      console.warn(
        `[flawless] ${path.join(ctx.outDir, "host/main.tsx")} predates the registry split:` +
          " it bakes in its own component tables, so newly analysed components cannot mount" +
          " through it, and no flag may rewrite a write-once file — delete host/main.tsx and" +
          " re-run (provider wiring regenerates from --provider), or port your hand wiring" +
          ' and import "./registry".',
      );
    }
    // A component that left the host set stops being rendered, but its profile
    // spec would otherwise sit in profile/ forever, failing at mount with
    // "unknown component" — the suite red by the tool's own doing. The sweep
    // retires the ones whose stamp proves them untouched tool output, and
    // names the ones it refused to touch (hand work or unprovable).
    const staleRemovedNote =
      res.staleRemoved.length > 0
        ? `; retired ${res.staleRemoved.length} stale profile spec(s) whose component left the host — ` +
          res.staleRemoved.map((f) => path.relative(path.resolve(ctx.outDir), f)).join(", ")
        : "";
    const staleKeptNote =
      res.staleKept.length > 0
        ? `; kept ${res.staleKept.length} stale profile spec(s) — ` +
          res.staleKept
            .map((f) => `${path.relative(path.resolve(ctx.outDir), f.abs)} (${f.verdict})`)
            .join(", ") +
          " (delete to retire)"
        : "";
    // The provider lives in a file the tool owns, but main.tsx's import of it
    // is kept — so when the provider moves, the kept harness mounts the OLD
    // provider and every mount fails on an opaque 5000ms timeout. scaffold
    // re-points that one line; the run has to say which host it re-pointed.
    const providerNote = res.providerImportRefresh
      ? `; re-pointed host/main.tsx's provider import ${res.providerImportRefresh.from} → ` +
        `${res.providerImportRefresh.to} (the harness is kept, this line is not)`
      : "";
    if (res.providerImportWarning) {
      console.warn(`[flawless] ${res.providerImportWarning}.`);
    }
    return {
      id: "perf-harness",
      ok: true,
      outputs: res.written,
      findings: [],
      status: res.status,
      summary:
        res.status === "refreshed"
          ? `refreshed perf suite for ${covered}${keptNote}${providerNote}${migrationNote}${staleRemovedNote}${staleKeptNote}`
          : `scaffolded perf suite for ${covered}${migrationNote}${staleRemovedNote}${staleKeptNote}`,
    };
  },
};
